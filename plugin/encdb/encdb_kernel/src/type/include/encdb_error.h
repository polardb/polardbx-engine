#pragma once

#define ENCDB_MK_ERROR(x) (0x80000000 | ((x) << 16) | 0x0000)

typedef enum EncdbStatus {
  ENCDB_STATUS_OK = (0x00000000 | (0)),

  ENCDB_EXCEPTION = ENCDB_MK_ERROR(0x7001),  // normally not used

  // Common exception
  ERROR_OUT_OF_MEMORY = ENCDB_MK_ERROR(
      0x7003),  // Not enough memory is available to complete this operation
  ENCDB_INVALID_PARAMETER_EXCEPTION =
      ENCDB_MK_ERROR(0x7007),  // The parameter is incorrect
  ENCDB_REMOTE_ATTESTATION_EXCEPTION = ENCDB_MK_ERROR(0x700A),
  ENCDB_UNSUPPORTED_OPERATION_EXCEPTION = ENCDB_MK_ERROR(0x700E),
  ENCDB_VERSION_MISMATCH_EXCEPTION = ENCDB_MK_ERROR(0x700F),
  ENCDB_INVALID_TEXT_REPRESENTATION =
      ENCDB_MK_ERROR(0x7010),  // ERRCODE_INVALID_TEXT_REPRESENTATION
  ENCDB_EXCEPTION_INVALID_DATABASE_DATA = ENCDB_MK_ERROR(0x7012),
  ENCDB_EXCEPTION_ACCESS_DENIED = ENCDB_MK_ERROR(0x7017),
  ENCDB_EXCEPTION_CACHE_MISS = ENCDB_MK_ERROR(0x7018),
  ENCDB_EXCEPTION_INVALID_TIMESTAMP = ENCDB_MK_ERROR(0x7019),

  ERROR_RESULT_OUT_OF_MEMORY = ENCDB_MK_ERROR(0x7102),
  // This one explicitly states that proxy does not reserve enough memory for
  // plaintext or ciphertext
  ERROR_NOT_ENOUGH_MEMORY_FROM_PROXY = ENCDB_MK_ERROR(0x7104),

  // Meta exception
  ENCDB_EXCEPTION_INVALID_JSON_DATA = ENCDB_MK_ERROR(0x7201),
  ENCDB_EXCEPTION_JSON_KEY_MISS = ENCDB_MK_ERROR(0x7202),
  ENCDB_EXCEPTION_NO_SUCH_SENSITIVE_ALGO = ENCDB_MK_ERROR(0x7203),
  ENCDB_EXCEPTION_NO_SUCH_MASK_ALGO = ENCDB_MK_ERROR(0x7204),

  // Crypto exception
  ERROR_CRYPTO = ENCDB_MK_ERROR(0x7600),
  ERROR_NO_SUCH_ALGORITHM = ENCDB_MK_ERROR(0x7601),
  ERROR_INVALID_KEY = ENCDB_MK_ERROR(0x7602),
  ERROR_INVALID_PARAMETER = ENCDB_MK_ERROR(0x7603),
  ERROR_BAD_PADDING = ENCDB_MK_ERROR(0x7604),
  ERROR_BAD_CIPHER = ENCDB_MK_ERROR(0x7605),
  ERROR_INVALID_CONTEXT_ID = ENCDB_MK_ERROR(0x7606),
  ERROR_CRYPTO_SYMMETRIC = ENCDB_MK_ERROR(0x7607),
  ERROR_CRYPTO_ASYMMETRIC = ENCDB_MK_ERROR(0x7608),
  ERROR_CRYPTO_HASH = ENCDB_MK_ERROR(0x7609),
  ERROR_CRYPTO_KDF = ENCDB_MK_ERROR(0x760A),
  ERROR_CRYPTO_HMAC = ENCDB_MK_ERROR(0x760B),
  ERROR_NO_SUCH_CIPHER_SUITE = ENCDB_MK_ERROR(0x760C),
  ERROR_MAC_MISMATCH = ENCDB_MK_ERROR(0x760D),  // verify mac mismatch
  ERROR_NO_SUCH_CC_FLAGS = ENCDB_MK_ERROR(0x760E),
  ERROR_INVALID_ENC_TYPE = ENCDB_MK_ERROR(0x760F),
  ERROR_NO_SUCH_TYPE = ENCDB_MK_ERROR(0x7610),
  ERROR_NO_SUCH_TEE_TYPE = ENCDB_MK_ERROR(0x7611),
  ERROR_NO_SUCH_CC_POLICY = ENCDB_MK_ERROR(0x7612),
  ENCDB_EXCEPTION_OLD_MEK_MISS = ENCDB_MK_ERROR(0x7618),

  ENCDB_EXCEPTION_KEY =
      ENCDB_MK_ERROR(0x7700),  // base status for key exception
  ENCDB_EXCEPTION_CC_MISS =
      ENCDB_MK_ERROR(0x7701),  // indicates the missing cipher context
  ENCDB_EXCEPTION_MEK_MISS =
      ENCDB_MK_ERROR(0x7702),  // indicates the missing mek
  ENCDB_EXCEPTION_MEK_REQUEST =
      ENCDB_MK_ERROR(0x7703),  // indicates requesting mek
  ENCDB_EXCEPTION_UNKNOWN_MEK_ID = ENCDB_MK_ERROR(0x7704),  // unknown mekid
  ENCDB_EXCEPTION_ENCLAVE_KEY_PAIR_MISS = ENCDB_MK_ERROR(0x7705),
  ENCDB_EXCEPTION_ENCLAVE_KEY_PAIR_REQUEST = ENCDB_MK_ERROR(0x7706),
  ENCDB_EXCEPTION_IMPORT_MEK = ENCDB_MK_ERROR(0x7707),
  ENCDB_EXCEPTION_UPDATE_MEK = ENCDB_MK_ERROR(0x7708),
  ENCDB_EXCEPTION_CONVERT_KMS_MEK = ENCDB_MK_ERROR(0x7709),
  ENCDB_EXCEPTION_GENERATE_DEK_FAILED = ENCDB_MK_ERROR(0x770A),
  ENCDB_EXCEPTION_UNKNOWN_MSG_TYPE = ENCDB_MK_ERROR(0x770B),
  ENCDB_EXCEPTION_RE_ENCRYPT_DEK_FAILED = ENCDB_MK_ERROR(0x770C),
  ENCDB_EXCEPTION_DEFAULT_CC_MISS = ENCDB_MK_ERROR(
      0x770D),  // missing default cipher context for current user
  ENCDB_EXCEPTION_INTERNAL_SQL_ERROR = ENCDB_MK_ERROR(0x770E),
  ENCDB_EXCEPTION_KEYNAME_MISS =
      ENCDB_MK_ERROR(0x770F),  // indicates the missing keyname
  ENCDB_EXCEPTION_GET_CURRENT_USER_FAILED =
      ENCDB_MK_ERROR(0x7710),  // get current user failed
  ENCDB_EXCEPTION_GET_CURRENT_DATABASE_FAILED =
      ENCDB_MK_ERROR(0x7711),  // get current database failed
  ENCDB_EXCEPTION_NOT_CURRENT_DATABASE = ENCDB_MK_ERROR(
      0x7712),  // the searching content is not in the current database
  ENCDB_EXCEPTION_KEY_HIERARCHY_MISS =
      ENCDB_MK_ERROR(0x7713),  // indicates the missing key hierarchy
  ENCDB_EXCEPTION_USER_NAME_MISS =
      ENCDB_MK_ERROR(0x7714),  // indicates the missing user name
  ENCDB_EXCEPTION_DATABASE_NAME_MISS =
      ENCDB_MK_ERROR(0x7715),  // indicates the missing database name
  ENCDB_EXCEPTION_SCHEMA_NAME_MISS =
      ENCDB_MK_ERROR(0x7716),  // indicates the missing schema name
  ENCDB_EXCEPTION_TABLE_NAME_MISS =
      ENCDB_MK_ERROR(0x7717),  // indicates the missing table name
  ENCDB_EXCEPTION_COLUMN_NAME_MISS =
      ENCDB_MK_ERROR(0x7718),  // indicates the missing column name
  ENCDB_EXCEPTION_KEYNAME_WRONG_FORMAT = ENCDB_MK_ERROR(0x7719),
  ENCDB_EXCEPTION_KEYNAME_WRONG_VERSION = ENCDB_MK_ERROR(0x771A),
  ENCDB_EXCEPTION_NO_SUCH_KEY_HIERARCHY_LEVEL = ENCDB_MK_ERROR(0x771B),
  ENCDB_EXCEPTION_NOT_SUPPORTED_DESENSITIZE_TYPE = ENCDB_MK_ERROR(0x771C),
  ENCDB_EXCEPTION_WRONG_DESENSITIZE_FORMAT = ENCDB_MK_ERROR(0x771D),
  ENCDB_EXCEPTION_MEK_ID_MISMATCH = ENCDB_MK_ERROR(0x771E),
  ENCDB_EXCEPTION_KMS_META_WRITE_FAILED =
      ENCDB_MK_ERROR(0x771F),  // failed to persist KMS metadata to system table
  ENCDB_EXCEPTION_KMS_META_DELETE_FAILED =
      ENCDB_MK_ERROR(0x7720),  // failed to delete KMS metadata from system table

  // enc rule exception
  ENCDB_EXCEPTION_IMPORT_ENC_RULE_FAILED = ENCDB_MK_ERROR(0x8001),

} EncdbStatus;

enum LogLevel {
  LL_DEBUG = 0,
  LL_INFO = LL_DEBUG,
  LL_WARNING,
  LL_ERROR,
};

