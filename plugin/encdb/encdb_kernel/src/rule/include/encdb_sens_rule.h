/*
 * When treating UserAccess with its pure numeric value, we always ensure that
 *     lower numeric value means lower access rights.
 */
enum UserAccess : int {
  NO_ACCESS = 0,      // Data should be encrypted by a random key. No one can
                      // retrieve plaintext from it.
  RESTRICTED_ACCESS,  // Data should be encrypted by user's own key. Only this
                      // user can decrypt it.
  FULL_ACCESS  // Data needs no encryption at all, and can be returned with
               // plaintext.
};
inline UserAccess strToUserAccess(const std::string &str) {
  if (str == "noneAccess") {
    return UserAccess::NO_ACCESS;
  } else if (str == "restrictedAccess") {
    return UserAccess::RESTRICTED_ACCESS;
  } else if (str == "fullAccess") {
    return UserAccess::FULL_ACCESS;
  } else {
    throw EncdbInvalidParameterException(str +
                                         " is not a valid UserAccess value");
  }
}
inline std::string userAccessToStr(UserAccess ua) {
  switch (ua) {
    case UserAccess::NO_ACCESS:
      return "noneAccess";
    case UserAccess::RESTRICTED_ACCESS:
      return "restrictedAccess";
    case UserAccess::FULL_ACCESS:
      return "fullAccess";
    default:
      throw EncdbInvalidParameterException(ua +
                                           " is not a valid UserAccess value");
  }
}
/*
 * When treating RuleType with its pure numeric value, we always ensure that
 * smaller numeric value means broader data source ranges. We catogorize all
 * existing rules to three types. Type 0 (USER_DEFINED): A user-specified rule,
 * which can cover multiple <db, tbl, col> pairs. Type 1 (TABLE_ORIENTED): A
 * auto-generated rule, which cover 1 <db, tbl> pair (but multiple <db, tbl,
 * col> pairs). Type 2 (COLUMN_ORIENTED): A auto-generated rule (caused by rule
 * spreading), its name must be generated with generatePreciseRuleName function.
 *           Such a rule can only be responsible to 1 <db, tbl, col> pair.
 * Assumption 0: All Type-0 rules (USER_DEFINED) are mutually exclusive
 * regarding data sources (i.e. the <db, tbl, col>s they cover) Assumption 1:
 * All Typo-1 rules (TABLE_ORIENTED) are mutually exclusive for the same <db,
 * tbl> datasource. Assumption 2: All Type-2 rules (COLUMN_ORIENTED) are
 * mutually exclusive for the same <db, tbl, col> datasource.
 *
 *     Obviously, for any datasource <db, tbl, col> there exists at most 1
 * type-0 rule, 1 type-1 rule and 1 type-2 rule that covers it.
 */
enum RuleType : int {
  USER_DEFINED = 0,  // A rule defined by user. Can cover multiple databases and
                     // multiple tables.
  TABLE_ORIENTED,    // A rule generated by encdb, can cover only 1 table, but
                     // might cover multiple columns.
  COLUMN_ORIENTED    // A rule generated by encdb, can cover only 1 table and 1
                     // column.
};
